CREATE TABLE admins (
  admin_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(254) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP
);
CREATE UNIQUE INDEX uq_admin_email_lower ON admins (LOWER(email));

CREATE TABLE pp_assets (
  asset_id UUID PRIMARY KEY,
  storage_key VARCHAR(300) NOT NULL UNIQUE,
  mime_type VARCHAR(100) NOT NULL,
  byte_size BIGINT NOT NULL CHECK (byte_size > 0),
  sha256 VARCHAR(64) NOT NULL,
  original_name VARCHAR(255) NOT NULL,
  state VARCHAR(20) NOT NULL CHECK (state IN ('READY','BLOCKED','ABORTED')),
  created_by BIGINT NOT NULL REFERENCES admins(admin_id),
  created_at TIMESTAMPTZ NOT NULL,
  unreferenced_since TIMESTAMPTZ
);
CREATE INDEX idx_pp_assets_cleanup ON pp_assets(state, unreferenced_since);

CREATE TABLE events (
  event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_type VARCHAR(20) NOT NULL DEFAULT 'PLAYPIT',
  slug VARCHAR(80) NOT NULL UNIQUE,
  title VARCHAR(200) NOT NULL,
  summary VARCHAR(300),
  description TEXT NOT NULL,
  main_image_url VARCHAR(2048),
  start_at TIMESTAMP NOT NULL,
  end_at TIMESTAMP NOT NULL,
  venue_name VARCHAR(300) NOT NULL,
  address VARCHAR(300),
  access TEXT,
  price VARCHAR(300),
  ticket_url VARCHAR(2048),
  cover_asset_id UUID REFERENCES pp_assets(asset_id),
  status VARCHAR(20) NOT NULL CHECK (status IN ('DRAFT','PUBLISHED','HIDDEN','ARCHIVED')),
  accepting_messages BOOLEAN NOT NULL DEFAULT FALSE,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
  CHECK (start_at < end_at)
);
CREATE INDEX idx_events_public ON events(status, start_at DESC, event_id DESC);

CREATE TABLE creators (
  creator_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug VARCHAR(80) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  name_kana VARCHAR(100),
  profile TEXT NOT NULL,
  concept TEXT,
  genre VARCHAR(80),
  profile_image_url VARCHAR(2048),
  website_url VARCHAR(2048),
  social_links JSONB NOT NULL DEFAULT '[]'::jsonb,
  status VARCHAR(20) NOT NULL CHECK (status IN ('DRAFT','PUBLISHED','HIDDEN','ARCHIVED')),
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP
);

CREATE TABLE artworks (
  artwork_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  creator_id BIGINT NOT NULL REFERENCES creators(creator_id),
  slug VARCHAR(80) NOT NULL UNIQUE,
  title VARCHAR(200) NOT NULL,
  description TEXT NOT NULL,
  background TEXT,
  concept TEXT,
  materials VARCHAR(300),
  production_year SMALLINT,
  main_image_url VARCHAR(2048),
  status VARCHAR(20) NOT NULL CHECK (status IN ('DRAFT','PUBLISHED','HIDDEN','ARCHIVED')),
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP
);
CREATE INDEX idx_artworks_creator ON artworks(creator_id, status, artwork_id);

CREATE TABLE event_creators (
  participation_id BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  event_id BIGINT NOT NULL REFERENCES events(event_id),
  creator_id BIGINT NOT NULL REFERENCES creators(creator_id),
  exhibition_title VARCHAR(200),
  display_order INTEGER NOT NULL CHECK (display_order >= 0),
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
  PRIMARY KEY(event_id, creator_id)
);
CREATE INDEX idx_event_creators_display ON event_creators(event_id, display_order, creator_id);

CREATE TABLE event_artworks (
  event_artwork_id BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  event_id BIGINT NOT NULL REFERENCES events(event_id),
  artwork_id BIGINT NOT NULL REFERENCES artworks(artwork_id),
  exhibition_area VARCHAR(150),
  display_order INTEGER NOT NULL CHECK (display_order >= 0),
  qr_code_url VARCHAR(2048),
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
  PRIMARY KEY(event_id, artwork_id)
);
CREATE INDEX idx_event_artworks_display ON event_artworks(event_id, display_order, artwork_id);

CREATE TABLE media_files (
  media_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  artwork_id BIGINT NOT NULL REFERENCES artworks(artwork_id),
  media_type VARCHAR(20) NOT NULL CHECK (media_type IN ('IMAGE','VIDEO','AUDIO')),
  url VARCHAR(2048) NOT NULL,
  alt_text VARCHAR(300),
  display_order INTEGER NOT NULL CHECK (display_order >= 0),
  created_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP
);

CREATE TABLE creator_links (
  link_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  creator_id BIGINT NOT NULL REFERENCES creators(creator_id),
  label VARCHAR(80) NOT NULL,
  url VARCHAR(2048) NOT NULL,
  display_order INTEGER NOT NULL CHECK (display_order >= 0),
  created_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP
);

CREATE TABLE pp_creator_assets (
  creator_id BIGINT NOT NULL REFERENCES creators(creator_id),
  asset_id UUID NOT NULL REFERENCES pp_assets(asset_id),
  purpose VARCHAR(20) NOT NULL CHECK (purpose IN ('ICON','PHOTO')),
  position INTEGER NOT NULL CHECK (position >= 0),
  PRIMARY KEY(creator_id, purpose, position),
  UNIQUE(asset_id)
);

CREATE TABLE pp_artwork_assets (
  artwork_id BIGINT NOT NULL REFERENCES artworks(artwork_id),
  asset_id UUID NOT NULL REFERENCES pp_assets(asset_id),
  purpose VARCHAR(20) NOT NULL CHECK (purpose IN ('IMAGE','AUDIO','VIDEO')),
  position INTEGER NOT NULL CHECK (position >= 0),
  PRIMARY KEY(artwork_id, purpose, position),
  UNIQUE(asset_id)
);

CREATE TABLE messages (
  message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id BIGINT NOT NULL REFERENCES events(event_id),
  creator_id BIGINT REFERENCES creators(creator_id),
  artwork_id BIGINT REFERENCES artworks(artwork_id),
  message TEXT NOT NULL CHECK (char_length(message) BETWEEN 1 AND 300),
  display_name VARCHAR(30),
  is_anonymous BOOLEAN NOT NULL,
  agreement BOOLEAN NOT NULL CHECK (agreement),
  status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING','PUBLISHED','HIDDEN','DELETED')),
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
  CHECK (creator_id IS NOT NULL OR artwork_id IS NOT NULL)
);
CREATE INDEX idx_messages_creator_public ON messages(event_id, creator_id, status, created_at DESC, message_id DESC);
CREATE INDEX idx_messages_artwork_public ON messages(event_id, artwork_id, status, created_at DESC, message_id DESC);

CREATE TABLE pp_subject_locks (
  subject_hash VARCHAR(64) PRIMARY KEY,
  last_used_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE pp_post_receipts (
  subject_hash VARCHAR(64) NOT NULL REFERENCES pp_subject_locks(subject_hash) ON DELETE CASCADE,
  request_key UUID NOT NULL,
  request_hash VARCHAR(64) NOT NULL,
  normalized_body_hash VARCHAR(64) NOT NULL,
  message_id BIGINT NOT NULL UNIQUE REFERENCES messages(message_id),
  accepted_at TIMESTAMPTZ NOT NULL,
  response_json JSONB NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  PRIMARY KEY(subject_hash, request_key)
);
CREATE INDEX idx_receipts_subject_time ON pp_post_receipts(subject_hash, accepted_at);
CREATE INDEX idx_receipts_duplicate ON pp_post_receipts(subject_hash, normalized_body_hash, accepted_at);

CREATE TABLE pp_reports (
  report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id BIGINT NOT NULL REFERENCES messages(message_id),
  category VARCHAR(20) NOT NULL CHECK (category IN ('RIGHTS','ABUSE','OTHER')),
  detail VARCHAR(1000) NOT NULL,
  state VARCHAR(20) NOT NULL CHECK (state IN ('OPEN','IN_REVIEW','CLOSED')),
  resolution VARCHAR(1000),
  subject_hash VARCHAR(64) NOT NULL,
  assigned_admin_id BIGINT REFERENCES admins(admin_id),
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP
);
CREATE INDEX idx_reports_state ON pp_reports(state, created_at DESC, report_id DESC);

CREATE TABLE pp_audit (
  audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_id BIGINT NOT NULL REFERENCES admins(admin_id),
  action VARCHAR(80) NOT NULL,
  target_type VARCHAR(40) NOT NULL,
  target_id VARCHAR(80) NOT NULL,
  result VARCHAR(40) NOT NULL,
  trace_id UUID NOT NULL,
  occurred_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE pp_metrics (
  metric_id UUID PRIMARY KEY,
  kind VARCHAR(30) NOT NULL CHECK (kind IN ('EVENT_VIEW','CREATOR_VIEW','ARTWORK_VIEW','MESSAGE_ACCEPTED')),
  event_id BIGINT NOT NULL REFERENCES events(event_id),
  creator_id BIGINT REFERENCES creators(creator_id),
  artwork_id BIGINT REFERENCES artworks(artwork_id),
  visitor_hash VARCHAR(64),
  occurred_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_metrics_kind_event ON pp_metrics(kind, event_id, occurred_at);

CREATE TABLE login_attempts (
  identity_hash VARCHAR(64) PRIMARY KEY,
  failures INTEGER NOT NULL,
  window_start TIMESTAMP NOT NULL,
  locked_until TIMESTAMP,
  updated_at TIMESTAMP NOT NULL
);
